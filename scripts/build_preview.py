"""Rebuild the offline editor preview after changing the public theme."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
html = (root / "index.html").read_text()
html = re.sub(
    r'<link rel="stylesheet" href="style\.css(?:\?[^\"]*)?">',
    lambda _: "<style>\n" + (root / "style.css").read_text() + "\n</style>",
    html,
)
for filename, content in [
    ("content.js", "/*LLW-DATA*/"),
    ("site-core.js", (root / "site-core.js").read_text()),
    ("app.js", (root / "app.js").read_text()),
]:
    html = re.sub(r'<script defer src="' + re.escape(filename) + r'(?:\?[^\"]*)?"></script>', "", html)
    content = content.replace("</script", "<\\/script")
    html = html.replace("</body>", "<script>\n" + content + "\n</script>\n</body>")
assert html.count("/*LLW-DATA*/") == 1
(root / "preview-template.js").write_text(
    "/* Offline editor preview, generated by scripts/build_preview.py. */\n"
    "window.LLW_PREVIEW_TEMPLATE = "
    + json.dumps(html, ensure_ascii=False).replace("<", "\\u003c")
    + ";\n"
)
print("Updated preview-template.js")
